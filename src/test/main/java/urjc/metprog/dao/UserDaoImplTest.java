package test.main.java.urjc.metprog.dao;

import main.java.urjc.metprog.dao.DatabaseManager;
import main.java.urjc.metprog.dao.UserDaoImpl;
import main.java.urjc.metprog.models.user.User;
import main.java.urjc.metprog.models.user.UserBuilder;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import java.util.List;

import static org.junit.jupiter.api.Assertions.*;

class UserDaoImplTest {

    private UserDaoImpl userDao;

    @BeforeEach
    void setUp() {
        DatabaseManager.useTestDatabase();
        DatabaseManager.createTables();
        userDao = new UserDaoImpl();
    }

    @AfterEach
    void tearDown() {
        DatabaseManager.useDefaultDatabase();
    }

    @Test
    void insertAndGetUser_ValidUser_ReturnsSameUser() {
        User original = new UserBuilder()
                .setName("Test User")
                .setNick("testnick")
                .setPassword("pass1234")
                .setRegistrationNumber("REG123")
                .setRole("player")
                .setBlocked(false)
                .build();

        userDao.insertUser(original);
        User recovered = userDao.getUser("testnick");

        assertNotNull(recovered);
        assertEquals(original.getName(), recovered.getName());
        assertEquals(original.getNick(), recovered.getNick());
        assertEquals(original.getRegistrationNumber(), recovered.getRegistrationNumber());
        assertEquals(original.getRole(), recovered.getRole());
        assertFalse(recovered.isBlocked());
    }

    @Test
    void updateUser_ChangesNameAndVictories_PersistsChanges() {
        User user = new UserBuilder().setNick("update_me").setName("Old Name").setPassword("pass").setVictories(0).build();
        userDao.insertUser(user);

        user.setName("New Name");
        user.setVictories(5);
        user.setBlocked(true);
        userDao.updateUser(user);

        User updated = userDao.getUser("update_me");
        assertEquals("New Name", updated.getName());
        assertEquals(5, updated.getVictories());
        assertTrue(updated.isBlocked());
    }

    @Test
    void deleteUser_RemovesFromDatabase() {
        userDao.insertUser(new UserBuilder().setNick("delete_me").setName("Del").setPassword("pass").build());
        assertNotNull(userDao.getUser("delete_me"));

        userDao.deleteUser("delete_me");
        assertNull(userDao.getUser("delete_me"));
    }

    @Test
    void getGlobalRanking_ReturnsUsersOrderedByVictories() {
        userDao.insertUser(new UserBuilder().setNick("user1").setName("U1").setPassword("p").setVictories(10).build());
        userDao.insertUser(new UserBuilder().setNick("user2").setName("U2").setPassword("p").setVictories(20).build());
        userDao.insertUser(new UserBuilder().setNick("user3").setName("U3").setPassword("p").setVictories(5).build());

        List<User> ranking = userDao.getGlobalRanking();
        assertEquals(3, ranking.size());
        assertEquals("user2", ranking.get(0).getNick());
        assertEquals("user1", ranking.get(1).getNick());
        assertEquals("user3", ranking.get(2).getNick());
    }

    @Test
    void getUserId_ReturnsCorrectId() {
        userDao.insertUser(new UserBuilder().setNick("find_my_id").setName("N").setPassword("p").build());
        int id = userDao.getUserId("find_my_id");
        assertTrue(id > 0, "ID should be a positive integer generated by DB");
    }
}
